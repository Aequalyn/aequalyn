#!/usr/bin/env bash
# 20261125-1.sh -- migration for existing installs: the calculator's key, and the screens.
#
# Super + = was both the calculator and "the main window larger": the calculator is on
# Super + Alt + C now, unless that is taken, and where its line is still the shipped one.
# monitors.lua shipped with the screens of one machine: where it is still exactly that
# file, and this is not that machine (it has no HDMI-A-4), the screens are found by
# themselves again.

set -euo pipefail

if [[ -z "${AEQUALYN_MIGRATION_HOMES:-}" ]]; then
    [[ $EUID -eq 0 ]] || { echo "run as root (sudo $0)" >&2; exit 1; }
    homes=(/home/* /root)
else
    homes=("$AEQUALYN_MIGRATION_HOMES"/*)
fi
drm=${AEQUALYN_MIGRATION_DRM:-/sys/class/drm}

info() { printf '\033[0;34m[20261125-1]\033[0m %s\n' "$*"; }
ok()   { printf '\033[0;32m[20261125-1]\033[0m %s\n' "$*"; }

shipped='-- Generated by Quickshell MonitorManager
hl.monitor({ output = "eDP-1", mode = "1920x1080@60.00", position = "4658x29", scale = 1 })
hl.monitor({ output = "HDMI-A-4", mode = "1920x1080@60.00", position = "2738x0", scale = 1 })'

for home in "${homes[@]}"; do
    hypr="$home/.config/hypr"
    f="$hypr/keybinds.lua"
    if [[ -f "$f" ]] && grep -qE '^hl\.bind\(M \.\. " \+ EQUAL", *hl\.dsp\.exec_cmd\("qs ipc call calculator toggle"\)\)' "$f"; then
        if grep -rqE '"[^"]*\+ *ALT *\+ *C"' "$hypr" --include='*.lua' 2>/dev/null; then
            info "$home: keeping the calculator's key, Super + Alt + C is taken"
        else
            sed -E 's/^hl\.bind\(M \.\. " \+ EQUAL", *(hl\.dsp\.exec_cmd\("qs ipc call calculator toggle"\))/hl.bind(M .. " + ALT + C",        \1/' "$f" > "$f.tmp"
            cat "$f.tmp" > "$f"
            rm -f "$f.tmp"
            info "$home: the calculator is on Super + Alt + C"
        fi
    fi
    m="$hypr/monitors.lua"
    if [[ -f "$m" && "$(cat "$m")" == "$shipped" ]] && ! compgen -G "$drm/card*-HDMI-A-4" > /dev/null; then
        echo '-- Generated by Quickshell MonitorManager' > "$m"
        info "$home: screens of another machine removed"
    fi
done

ok "migration 20261125-1 complete"
