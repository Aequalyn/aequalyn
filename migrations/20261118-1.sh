#!/usr/bin/env bash
# 20261118-1.sh -- replace every user's ~/.config/hypr with the shipped defaults, once.
#
# The Hyprland config was split into sections: hyprland.lua now includes
# environment.lua, autostart.lua, input.lua, workspaces.lua, keybinds.lua and
# window-rules.lua next to it, and each of those defines what it needs itself
# (HOME included -- a dofile'd file never saw hyprland.lua's locals, which is
# what broke the first split attempt). The plugin-managed altscape block lives
# only at the end of hyprland.lua, where the Altscape plugin rewrites it.
#
# Updates deliberately leave a user's hypr folder alone, so machines still on
# the old single-file config would never receive the split. This migration
# replaces ~/.config/hypr outright with the newest shipped folder, generated
# files included (monitors.lua, webapps.lua, look.lua, colors.lua, ...),
# because that is required for future development. Aequalyn has already saved
# what was there in ~/.local/state/aequalyn/backups/before-update-*.tar.gz;
# run by hand, make that copy yourself first.
#
# It defers (exit 3, tried again on the next update) while the tree it runs
# from still carries the old single-file config, so an update can never roll a
# machine back to it.
#
# Usage:  sudo bash 20261118-1.sh        (run by aequalyn-update, or by hand)

set -euo pipefail

[[ $EUID -eq 0 ]] || { echo "run as root (sudo $0)" >&2; exit 1; }

SRC="$(cd "$(dirname "$(readlink -f "$0")")/../config/hypr" && pwd)"

info() { printf '\033[0;34m[20261118-1]\033[0m %s\n' "$*"; }
ok()   { printf '\033[0;32m[20261118-1]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[20261118-1]\033[0m %s\n' "$*"; }

[[ -f "$SRC/hyprland.lua" ]] || { warn "no shipped Hyprland config at $SRC"; exit 1; }
if ! grep -q 'include("keybinds.lua")' "$SRC/hyprland.lua"; then
    warn "the newest Aequalyn still has the old single-file Hyprland config;"
    warn "not replacing anything. It is tried again on the next update."
    exit 3
fi

warn "This update will replace the hypr folder with the defaults, since it is required for future development."

replaced=0

for home in /home/* /root; do
    [[ -d "$home" ]] || continue
    hypr="$home/.config/hypr"
    [[ -e "$hypr" ]] || continue   # not an Aequalyn install: leave it alone
    owner=$(stat -c '%u:%g' "$hypr")
    uid=${owner%%:*}
    if cmp -s "$SRC/hyprland.lua" "$hypr/hyprland.lua" 2>/dev/null; then
        ok "$hypr already matches the shipped config"
        continue
    fi
    info "replacing $hypr"
    # The user's webapps.lua is generated by aequalyn-webapp for the apps they
    # have (their keybinds with them); the shipped tree carries none, so a
    # generated one is kept across the replacement.
    keep_lua=""
    if [[ -f "$hypr/webapps.lua" ]] && head -n 1 "$hypr/webapps.lua" | grep -q 'Generated by aequalyn-webapp'; then
        keep_lua=$(mktemp)
        cp "$hypr/webapps.lua" "$keep_lua"
    fi
    rm -rf "$hypr"
    cp -r "$SRC" "$hypr"
    if [[ -n "$keep_lua" ]]; then
        cp "$keep_lua" "$hypr/webapps.lua"
        rm -f "$keep_lua"
    fi
    chown -R "$owner" "$hypr"
    replaced=$((replaced + 1))
    ok "$hypr replaced with the shipped defaults"
    # let a running session use them right away (best effort; the next reload
    # or login does it otherwise)
    if [[ -d "/run/user/$uid/hypr" ]] && command -v runuser >/dev/null 2>&1; then
        runuser -u "#$uid" -- env XDG_RUNTIME_DIR="/run/user/$uid" hyprctl reload >/dev/null 2>&1 \
            && ok "Hyprland reloaded for uid $uid" \
            || warn "could not reload Hyprland for uid $uid; it happens on the next reload or login"
    fi
done

if [[ $replaced -eq 0 ]]; then
    ok "nothing replaced (every hypr folder already matches the shipped config)"
else
    ok "replaced the hypr folder of $replaced user(s)"
fi
