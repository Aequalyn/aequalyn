#!/usr/bin/env python3
"""python3 tests/test_migration_keys.py -- the calculator's key and the shipped screens on existing installs"""
import os, pathlib, subprocess, sys, tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
MIG = ROOT / "migrations/20261125-1.sh"
OLD = 'hl.bind(M .. " + EQUAL",          hl.dsp.exec_cmd("qs ipc call calculator toggle"))   -- Calculator\n'
NEW = 'hl.bind(M .. " + ALT + C",        hl.dsp.exec_cmd("qs ipc call calculator toggle"))   -- Calculator\n'
SCREENS = """-- Generated by Quickshell MonitorManager
hl.monitor({ output = "eDP-1", mode = "1920x1080@60.00", position = "4658x29", scale = 1 })
hl.monitor({ output = "HDMI-A-4", mode = "1920x1080@60.00", position = "2738x0", scale = 1 })
"""
EMPTY = "-- Generated by Quickshell MonitorManager\n"
fails = 0


def ok(cond, what):
    global fails
    if not cond:
        fails += 1
        print("FAIL", what)


def run(keys, screens, hdmi=False, extra=None):
    with tempfile.TemporaryDirectory() as tmp:
        tmp = pathlib.Path(tmp)
        hypr = tmp / "homes/u/.config/hypr"
        hypr.mkdir(parents=True)
        (tmp / "homes/empty").mkdir()
        (tmp / "drm").mkdir()
        if hdmi:
            (tmp / "drm/card1-HDMI-A-4").mkdir()
        (hypr / "keybinds.lua").write_text(keys)
        (hypr / "monitors.lua").write_text(screens)
        if extra:
            (hypr / "user.lua").write_text(extra)
        for _ in range(2):
            r = subprocess.run(["bash", str(MIG)], capture_output=True, text=True,
                               env=dict(os.environ, AEQUALYN_MIGRATION_HOMES=str(tmp / "homes"), AEQUALYN_MIGRATION_DRM=str(tmp / "drm")))
            ok(r.returncode == 0, "it runs: " + r.stderr)
        ok(sorted(p.name for p in hypr.iterdir()) == sorted(["keybinds.lua", "monitors.lua"] + (["user.lua"] if extra else [])), "nothing left behind")
        return (hypr / "keybinds.lua").read_text(), (hypr / "monitors.lua").read_text()


ok(run("a\n" + OLD + "b\n", SCREENS) == ("a\n" + NEW + "b\n", EMPTY), "the shipped ones are replaced")
ok(run(OLD, SCREENS, hdmi=True) == (NEW, SCREENS), "the machine they came from keeps its screens")
ok(run(OLD, SCREENS.replace("4658x29", "0x0"))[1] == SCREENS.replace("4658x29", "0x0"), "someone's own screens stay")
mine = 'hl.bind(M .. " + EQUAL", hl.dsp.exec_cmd("my-own"))\n'
ok(run(mine, EMPTY) == (mine, EMPTY), "someone's own key stays")
ok(run(OLD, EMPTY, extra='hl.bind("SUPER + ALT + C", x)\n')[0] == OLD, "a taken key is kept")
shipped = (ROOT / "config/hypr/keybinds.lua").read_text()
ok(NEW in shipped and '" + EQUAL"' not in shipped, "what ships has the new key")
ok("hl.monitor" not in (ROOT / "config/hypr/monitors.lua").read_text(), "no screens ship")
print(f"migration keys: {fails} failures")
sys.exit(1 if fails else 0)
